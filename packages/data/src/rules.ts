/**
 * Правила мира: числа, которые можно менять на ходу, не начиная мир заново, и их значения по умолчанию. Данные, а не
 * код симуляции: их читают и симуляция, и настройки карты в меню, и сервер (server/settings.ts).
 */

/** Во сколько раз чинить быстрее, чем строить, по умолчанию: полностью разбитое чинится за половину времени стройки. См. Sim.rules. */
export const REPAIR_SPEED = 2
/** Какую долю цены здания или юнита стоит починить его с нуля до целого, по умолчанию. Платят по мере починки. См. Sim.rules. */
export const REPAIR_COST = 0.5
/**
 * Сколько секунд после попадания цель не чинится, по умолчанию. Иначе один строитель за стеной отменяет осаду:
 * он возвращает больше прочности в секунду, чем бьёт отряд. Ремонт — между боями, а не под огнём. См. Sim.rules.
 */
export const REPAIR_PAUSE = 3

/** Числа правил, которые можно менять на ходу, не начиная мир заново. */
export interface Rules {
  /** Во сколько раз чинить быстрее, чем строить. Ноль — ремонта нет. */
  repairSpeed: number
  /** Какую долю цены здания или юнита стоит починить его с нуля до целого. */
  repairCost: number
  /** Сколько секунд после попадания цель не чинится: ремонт — между боями, а не под огнём. Ноль — чинят и под огнём. */
  repairPause: number
  /** Дерево технологий: здание строится, когда стоят нужные для него, см. REQUIRES. Выключено — открыто всё. */
  techTree: boolean
  /**
   * Замедление наземных юнитов по местности, доля скорости от 0 до 1: колёсная техника (vehicle), гусеничная
   * (heavy) и пехота — на песке и на болоте. По скале все идут в полную силу, летающим местность не мешает.
   */
  vehicleSand: number
  vehicleSwamp: number
  heavySand: number
  heavySwamp: number
  infantrySand: number
  infantrySwamp: number
  /** Замедление пехоты у подножия обрыва: она лезет, технике же туда нельзя вовсе. */
  infantryCliff: number
  /** Какая доля болотного замедления остаётся на солончаках: там болото промёрзло. */
  frozenSwamp: number
  /** Какую долю прочности в секунду теряет наземный юнит в едком болоте красных пустошей. */
  toxicSwamp: number
  /**
   * Доход игрока не в сети: offlineIncome — доля обычного, offlineMinutes — потолок за одно отсутствие, в минутах
   * обычного дохода. Без дохода совсем вернувшегося ждала бы неотремонтированная база: починка тратит кредиты.
   */
  offlineIncome: number
  offlineMinutes: number
  /** Защита новичка: сколько минут после появления игрока нельзя атаковать, см. shelter.ts. Ноль — защиты нет. */
  protection: number
  /**
   * Темп исследований, см. priceOf в topics.ts. researchGrowth — во сколько раз каждый ярус сложности дороже и дольше
   * предыдущего; researchScale — во сколько раз дороже, чем в матче; researchSlow — во сколько раз дольше: цену держит
   * земля (харит конечен), и растянуть срок ценой нельзя. Числа по умолчанию — дерево на один матч; на сервере, где
   * мир живёт две недели, они больше, см. server/settings.ts.
   */
  researchScale: number
  researchGrowth: number
  researchSlow: number
  /** Во сколько раз уровни зданий дороже и дольше, чем в матче, см. upgradeCost. */
  upgradeScale: number
  /**
   * Через сколько минут после выработки месторождения в другом месте карты появляется новое, см. renewal.ts. Ноль —
   * месторождения конечны.
   */
  depositRenewal: number
  /**
   * Лимит армии игрока: сколько места (SUPPLY в units.ts) занимают его юниты и заказы в очередях вместе. Заказ сверх
   * лимита не принимается; ноль — лимита нет. Держит и хост: тысячи юнитов на игрока он не разошлёт.
   */
  armyLimit: number
  /**
   * Юниты тратят боеприпасы из магазина и пополняют его в своей сети, см. supply.ts. Выключено — стреляют бесплатно:
   * так в бою армий и сценках меню, где сетей нет.
   */
  unitAmmo: boolean
}

